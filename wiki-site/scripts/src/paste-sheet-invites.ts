#!/usr/bin/env node
/**
 * Generates INVITE_PASTE_SHEET.txt — everybody who has an invite post, with their Quora profile
 * address, in groups of 20, ready to paste into a Quora post that lists who has been invited so
 * far.
 *
 * Why groups: one Quora post carrying every profile address reads as spam, so the list goes up 20
 * at a time (owner directive, 2026-10-14). Groups are numbered oldest first, so a group never
 * changes once it is full: a new invite joins the last group, or starts the next one.
 *
 * What counts as an invite post: the same contract as build-invites.ts, a listed post in
 * content/posts titled "An invitation to <name>". The address is the first Quora profile address
 * in the post, which is the credit line every invite carries. The name is the text the post puts
 * in front of that address when it is short enough to be a name, and the name in the title
 * otherwise.
 *
 * Order: by feed number (content/feed-numbers.json), which is publication order.
 *
 * Plain text for Quora's editor: each address sits inside a line beside the name, never alone on a
 * line, so the editor leaves it as written instead of turning it into a preview card.
 *
 * Usage:  pnpm wiki:paste-invites   (run wiki:sync first, so a new post has its feed number)
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFrontMatter } from './frontmatter.js';
import { feedEntries } from './feed-numbers.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const BLOG_ROOT = resolve(__dirname, '../..');
const POSTS_DIR = resolve(BLOG_ROOT, 'content/posts');
const OUT = resolve(BLOG_ROOT, 'INVITE_PASTE_SHEET.txt');

const SITE = 'https://chargingthefuture.github.io/chargingthefuture';
const INVITE_TITLE = /^An invitation to\s+(.+?)\.?$/i;
const PROFILE = /https?:\/\/(?:www\.)?quora\.com\/profile\/[^\s)\]]+/i;
const GROUP_SIZE = 20;
const RULE = '='.repeat(78);

type Invited = { name: string; profile: string; number: number; date: string; slug: string };

/** The name a post writes in front of the profile address, when that text is short enough to be a name. */
function nameBeforeAddress(body: string, address: string): string | null {
  const at = body.indexOf(address);
  if (at < 0) return null;
  const before = body.slice(Math.max(0, body.lastIndexOf('\n', at) + 1), at);
  // "Name (address)" or "[Name](address)"
  const link = /\[([^\]]+)\]\($/.exec(before);
  const plain = /([^.()[\]\n]+?)\s*\($/.exec(before);
  const raw = (link?.[1] ?? plain?.[1] ?? '').replace(/[.\s]+$/, '').trim();
  if (!raw || raw.split(/\s+/).length > 4 || /[,:;]/.test(raw)) return null;
  return raw;
}

function collect(): Invited[] {
  const numbers = new Map(feedEntries(BLOG_ROOT).map((e) => [`${e.repo}/${e.slug}`, e.number]));
  const people: Invited[] = [];
  for (const entry of readdirSync(POSTS_DIR, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.toLowerCase().endsWith('.md')) continue;
    const file = join(POSTS_DIR, entry.name);
    const { meta, body } = parseFrontMatter(readFileSync(file, 'utf8'));
    if (!meta || !meta.title || meta.listed === false) continue;
    const match = INVITE_TITLE.exec(String(meta.title).trim());
    if (!match) continue;
    const slug = meta.slug ?? relative(POSTS_DIR, file).replace(/\\/g, '/').replace(/\.md$/i, '');
    const repo = meta.repo ?? 'chargingthefuture/wiki-site';
    const address = PROFILE.exec(body)?.[0];
    if (!address) {
      console.warn(`skipped ${entry.name}: no Quora profile address in the post`);
      continue;
    }
    const number = numbers.get(`${repo}/${slug}`);
    if (number === undefined) {
      console.warn(`skipped ${entry.name}: no feed number yet (run wiki:sync first)`);
      continue;
    }
    people.push({
      name: nameBeforeAddress(body, address) ?? match[1].trim(),
      profile: address,
      number,
      date: String(meta.date ?? ''),
      slug,
    });
  }
  return people.sort((a, b) => a.number - b.number);
}

function longDate(iso: string): string {
  const d = new Date(`${iso}T12:00:00Z`);
  return d.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
}

function render(people: Invited[]): string {
  const groups: Invited[][] = [];
  for (let i = 0; i < people.length; i += GROUP_SIZE) groups.push(people.slice(i, i + GROUP_SIZE));

  const out: string[] = [
    'INVITE PASTE SHEET — everybody with an invite post, with their Quora profile address,',
    `${GROUP_SIZE} to a group, oldest first. Generated by pnpm wiki:paste-invites; never hand-edit.`,
    '',
    'Paste one group per Quora post. Every address in one post would read as spam, so the list',
    'goes up a group at a time. A full group never changes; a new invite joins the last group or',
    'starts the next one.',
    '',
    `${people.length} people in ${groups.length} group${groups.length === 1 ? '' : 's'}.`,
    '',
  ];

  groups.forEach((group, g) => {
    const first = g * GROUP_SIZE + 1;
    const last = first + group.length - 1;
    out.push(RULE);
    out.push(
      `Group ${g + 1} · invitations ${first} to ${last} · ${longDate(group[0].date)} to ${longDate(group[group.length - 1].date)}`,
    );
    out.push('');
    out.push(`People I have invited to the Skills Economy, part ${g + 1}:`);
    out.push('');
    group.forEach((p, i) => out.push(`${first + i}. ${p.name} (${p.profile})`));
    out.push('');
    out.push(`Every invitation is on the blog, at the top of the feed: ${SITE}/feed`);
    out.push('');
  });

  return `${out.join('\n').trimEnd()}\n`;
}

function main() {
  const people = collect();
  writeFileSync(OUT, render(people), 'utf8');
  console.log(`✓ Wrote ${people.length} invited people → ${relative(BLOG_ROOT, OUT)}`);
}

main();
